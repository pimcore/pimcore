namespace Pimcore\Model\Asset\MetaData\ClassDefinition\Data;

interface IdRewriterInterface
{
    /**
     * Rewrites id from source to target, $rewriteConfig contains
     * array(
     *  "document" => array(
     *      SOURCE_ID => TARGET_ID,
     *      SOURCE_ID => TARGET_ID
     *  ),
     *  "object" => array(...),
     *  "asset" => array(...)
     * )
     *
     * @param mixed $data the raw metadata value, as stored on the asset (e.g. an element id)
     *
     * @return mixed rewritten data based on data type
     */
    public function rewriteIds(mixed $data, array $rewriteConfig, array $params = []): mixed;
}
